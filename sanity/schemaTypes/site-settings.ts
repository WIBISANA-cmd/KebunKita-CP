import { defineField, defineType } from "sanity";

export const siteSettings = defineType({
  name: "siteSettings",
  title: "Pengaturan Toko",
  type: "document",
  groups: [
    { name: "identity", title: "Identitas", default: true },
    { name: "contact", title: "Kontak" },
    { name: "location", title: "Lokasi" },
    { name: "hours", title: "Jam Buka" },
    { name: "reputation", title: "Rating" },
    { name: "social", title: "Media Sosial" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "storeName",
      title: "Nama toko",
      type: "string",
      group: "identity",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "tagline",
      title: "Slogan",
      type: "string",
      group: "identity",
      description: "Muncul di bawah logo pada footer.",
    }),
    defineField({
      name: "description",
      title: "Deskripsi toko",
      type: "text",
      rows: 3,
      group: "identity",
    }),
    defineField({
      name: "logo",
      title: "Logo",
      type: "imageWithAlt",
      group: "identity",
      description: "Selama kosong, website memakai ikon daun sementara.",
    }),
    defineField({ name: "phone", title: "Telepon", type: "string", group: "contact" }),
    defineField({
      name: "whatsapp",
      title: "WhatsApp",
      type: "string",
      group: "contact",
      description: "Tulis dengan kode negara tanpa tanda plus, contoh 6281234567890.",
      validation: (rule) => rule.regex(/^\d{8,16}$/, { name: "nomor WhatsApp" }),
    }),
    defineField({ name: "email", title: "Email", type: "string", group: "contact" }),
    defineField({
      name: "addressLine",
      title: "Alamat",
      type: "string",
      group: "location",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "addressNote",
      title: "Catatan alamat",
      type: "string",
      group: "location",
      description: "Patokan lokasi. Kosongkan jika alamat sudah lengkap.",
    }),
    defineField({ name: "locality", title: "Kabupaten atau kota", type: "string", group: "location" }),
    defineField({ name: "region", title: "Provinsi", type: "string", group: "location" }),
    defineField({ name: "postalCode", title: "Kode pos", type: "string", group: "location" }),
    defineField({
      name: "latitude",
      title: "Latitude",
      type: "number",
      group: "location",
      validation: (rule) => rule.required().min(-90).max(90),
    }),
    defineField({
      name: "longitude",
      title: "Longitude",
      type: "number",
      group: "location",
      validation: (rule) => rule.required().min(-180).max(180),
    }),
    defineField({
      name: "mapsUrl",
      title: "Tautan Google Maps",
      type: "url",
      group: "location",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "openingHours",
      title: "Jam buka mingguan",
      type: "array",
      group: "hours",
      of: [{ type: "openingHours" }],
      description: "Isi satu baris untuk setiap hari. Status buka atau tutup dihitung otomatis dengan zona WIB.",
      validation: (rule) => rule.max(7),
    }),
    defineField({
      name: "hoursNote",
      title: "Catatan jam buka",
      type: "string",
      group: "hours",
      description: "Contoh: jam berbeda saat hari libur nasional.",
    }),
    defineField({
      name: "rating",
      title: "Rating Google Maps",
      type: "number",
      group: "reputation",
      description: "Salin dari Google Maps. Kosongkan jika belum ada.",
      validation: (rule) => rule.min(1).max(5),
    }),
    defineField({
      name: "reviewCount",
      title: "Jumlah ulasan",
      type: "number",
      group: "reputation",
      validation: (rule) => rule.integer().min(0),
    }),
    defineField({
      name: "socials",
      title: "Media sosial",
      type: "array",
      group: "social",
      of: [{ type: "socialLink" }],
    }),
    defineField({ name: "seoTitle", title: "Judul halaman", type: "string", group: "seo" }),
    defineField({
      name: "seoDescription",
      title: "Deskripsi halaman",
      type: "text",
      rows: 3,
      group: "seo",
      validation: (rule) => rule.max(170),
    }),
    defineField({
      name: "ogImage",
      title: "Gambar saat dibagikan",
      type: "imageWithAlt",
      group: "seo",
      description: "Ukuran ideal 1200 x 630 piksel.",
    }),
  ],
  preview: { prepare: () => ({ title: "Pengaturan Toko" }) },
});
